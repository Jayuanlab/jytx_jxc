process.env.STORE_DB_PATH = ":memory:";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { readStore } = require("../server/src/repository");
const { applyTestBatch } = require("../server/src/test-data-import");
const { inspect, collect } = require("../server/src/guardian");
const batch = JSON.parse(fs.readFileSync("data/imports/test-stock-2026-10-07.json", "utf8"));
const store = readStore();
applyTestBatch(store, batch);
assert.deepEqual(inspect(store), []);
const a = store.inventory.find((x) => x.serials?.length);
const b = store.inventory.find((x) => x !== a && x.serials?.length);
b.serials.push({ ...a.serials[0] });
const issues = inspect(store);
assert.ok(issues.some((x) => x.id.startsWith("duplicate-serial:")));
assert.ok(issues.some((x) => x.id.startsWith("serial-balance:")));
const result = collect(store);
assert.equal(result.findings, issues.length);
const before = store.feishuNotices.length;
collect(store);
assert.equal(store.feishuNotices.length, before);
console.log(JSON.stringify({ guardian: "passed", detected: issues.length, noticesDeduplicated: true }));