const assert=require('node:assert/strict');
const {readStore}=require('../server/src/repository');
const erp=require('../server/src/erp');
const gov=require('../server/src/gov-subsidy');
const store=JSON.parse(JSON.stringify(readStore()));
const owner=store.users.find((u)=>u.roleCode==='owner');
const stock=store.inventory.find((s)=>s.quantity>0 && (s.serials||[]).some((n)=>['可售','未激活'].includes(n.status)) && gov.classify(store.products.find((p)=>p.skuId===s.skuId)));
assert.ok(stock,'需要有可售测试手机');
const serial=stock.serials.find((n)=>['可售','未激活'].includes(n.status)).no;
const start=store.receipts.length;
const price=1099, subsidyAmount=164.85;
const input={saleMode:'guobu',account:'云闪付',platformOrderNo:'TEST-GOV-ORDER-001',subsidyAmount,accountOwnerId:owner.id,items:[{skuId:stock.skuId,quantity:1,salePrice:price,serialNo:serial}]};
assert.throws(()=>gov.prepare(store,{...input,subsidyAmount:501}),/补贴金额超过/);
assert.throws(()=>gov.prepare(store,{...input,items:[input.items[0],input.items[0]]}),/单件单独/);
const sale=erp.sale(store,owner,input);
assert.equal(sale.amount,price);assert.equal(sale.receivedAmount,0);require('../server/src/sale-payments').confirm(store,owner,{orderId:sale.id,actualAmount:934.15,reference:'TEST-GOV-CUSTOMER-PAY'});assert.equal(store.sales.find(row=>row.id===sale.id).receivedAmount,934.15);assert.equal(store.receipts.at(-1).amount,934.15);
assert.throws(()=>gov.prepare(store,input),/已使用/);
let claim=gov.claims(store,owner).find((x)=>x.orderId===sale.id);assert.equal(claim.subsidyAmount,subsidyAmount);
assert.throws(()=>erp.returnSale(store,owner,{orderId:sale.id,items:[{itemId:sale.items[0].id,quantity:1}],reason:'测试',account:'云闪付'}),/退款流水号/);
gov.confirm(store,owner,{id:claim.id,amount:subsidyAmount,statementNo:'TEST-GOV-ST'});
gov.receive(store,owner,{id:claim.id,amount:subsidyAmount,bankRef:'TEST-GOV-BANK',account:'银行卡'});
const returned=erp.returnSale(store,owner,{orderId:sale.id,items:[{itemId:sale.items[0].id,quantity:1}],reason:'测试退货',account:'云闪付',platformRefundRef:'TEST-GOV-REFUND'});
assert.equal(returned.amount,price);assert.equal(returned.customerRefund,934.15);assert.equal(returned.subsidyReversal,subsidyAmount);
assert.equal(store.receipts.at(-1).amount,-934.15);
claim=gov.claims(store,owner).find((x)=>x.id===claim.id);assert.equal(claim.refundDue,subsidyAmount);
gov.refund(store,owner,{id:claim.id,amount:subsidyAmount,bankRef:'TEST-GOV-REFUND-BANK',account:'银行卡'});
assert.equal(store.receipts.at(-1).amount,-subsidyAmount);
assert.equal(gov.claims(store,owner).find((x)=>x.id===claim.id).refundDue,0);
assert.equal(store.receipts.length-start,4);
console.log(JSON.stringify({govSubsidy:'passed',customerPaid:934.15,subsidyInTransit:164.85,fullReturn:true,refundChannelsSeparated:true,liveDatabaseChanged:false}));