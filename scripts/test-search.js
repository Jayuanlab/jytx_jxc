process.env.STORE_DB_PATH = ":memory:";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { readStore } = require("../server/src/repository");
const { applyTestBatch } = require("../server/src/test-data-import");
const { search } = require("../server/src/search");
const erp = require("../server/src/erp");
const batch = JSON.parse(fs.readFileSync("data/imports/test-stock-2026-10-07.json", "utf8"));
const store = readStore();
applyTestBatch(store, batch);
const owner = store.users.find((u) => u.roleCode === "owner");
const employee = store.users.find((u) => u.roleCode === "employee");
const phone = batch.products.find((p) => p.trackSerial && p.type === "智能机");
const accessory = batch.products.find((p) => !p.trackSerial);
const query = (text) => new URLSearchParams(text);
assert.equal(search(store, owner, query("scope=inventory&q=" + encodeURIComponent(phone.serials[0]))).results.inventory.length, 1);
assert.equal(search(store, owner, query("scope=inventory&q=" + encodeURIComponent(accessory.externalCode))).results.inventory.length, 1);
assert.equal(search(store, owner, query("scope=inventory&warehouse=销售仓")).results.inventory.length, 100);
assert.equal(search(store, owner, query("scope=suppliers&supplier=示例")).results.suppliers.length, 2);
assert.equal(search(store, employee, query("scope=meta")).suppliers.length, 0);
const sale = erp.sale(store, owner, { account: "微信", items: [{ skuId: phone.skuId, quantity: 1, salePrice: phone.salePrice, serialNo: phone.serials[0] }] });
assert.equal(search(store, owner, query("scope=sales&q=" + encodeURIComponent(sale.id))).results.sales.length, 1);
assert.equal(search(store, employee, query("scope=sales&q=" + encodeURIComponent(sale.id))).results.sales.length, 0);
assert.equal(search(store, employee, query("scope=inventory&q=" + encodeURIComponent(accessory.externalCode))).results.inventory[0].stockValue, undefined);
assert.throws(() => search(store, owner, query("scope=all")), /查询条件/);
console.log(JSON.stringify({ search: "passed", stock: batch.products.length, serial: phone.serials.length }));