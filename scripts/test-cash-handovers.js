const assert = require("node:assert/strict");
const c = require("../server/src/common");
const handovers = require("../server/src/cash-handovers");
const owner = { id:"owner", name:"老板", roleCode:"owner", status:"active", permissions:[] };
const wife = { id:"wife", name:"采购经手人", roleCode:"employee", status:"active", permissions:["finance:view"] };
const seller = { id:"staff", name:"营业员", roleCode:"employee", status:"active", permissions:["sale:create"] };
const other = { id:"other", name:"其他员工", roleCode:"employee", status:"active", permissions:["sale:create"] };
const store = c.initialize({users:[owner,wife,seller,other]});
const a = handovers.create(store,seller,{kind:"person",recipientId:wife.id,amount:285.40,note:"晚班现金"});
assert.equal(a.status,"待接收人确认");
assert.equal(store.receipts.length,0,"交接不能重复计为营业收入");
assert.equal(handovers.list(store,other).length,0);
assert.throws(()=>handovers.confirm(store,seller,{id:a.id,actualAmount:285.40}),/指定接收人/);
assert.throws(()=>handovers.confirm(store,wife,{id:a.id,actualAmount:280}),/金额不同/);
assert.equal(handovers.list(store,wife).length,1);
handovers.reject(store,wife,{id:a.id,countedAmount:280,reason:"实点少 5.40 元"});
assert.equal(a.status,"金额有异议");
assert.throws(()=>handovers.confirm(store,wife,{id:a.id,actualAmount:285.40}),/已经处理/);
const b=handovers.create(store,seller,{kind:"person",recipientId:wife.id,amount:280,note:"复点后重新提交"});
handovers.confirm(store,wife,{id:b.id,actualAmount:280});
assert.equal(b.status,"已确认收到");
const bank=handovers.create(store,seller,{kind:"bank",recipientId:owner.id,amount:100,note:"现金缴存"});
assert.throws(()=>handovers.confirm(store,owner,{id:bank.id,actualAmount:100}),/流水号/);
handovers.confirm(store,owner,{id:bank.id,actualAmount:100,bankRef:"BANK-001"});
assert.equal(bank.status,"已确认收到");
assert.equal(store.receipts.length,0);
const shot = require("../server/src/daily-close").snapshot(store, c.day());
assert.equal(shot.cashHandoverConfirmed, 380);
assert.equal(shot.cashHandoverPending.length, 0);
assert.ok(store.operationLogs.some((x)=>x.action==="cash-handover:confirm"));
console.log("cash handover rules passed");

