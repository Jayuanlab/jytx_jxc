process.env.STORE_DB_PATH = ":memory:";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const { readStore } = require("../server/src/repository");
const { applyTestBatch } = require("../server/src/test-data-import");
const erp = require("../server/src/erp");
const shift = require("../server/src/closeouts");
const batch = JSON.parse(fs.readFileSync("data/imports/test-stock-2026-10-07.json", "utf8"));
const store = readStore();
applyTestBatch(store, batch);
const owner = store.users.find((u) => u.roleCode === "owner");
const employee = store.users.find((u) => u.roleCode === "employee");
const accessory = batch.products.find((p) => !p.trackSerial && p.quantity >= 2);
const sale = erp.sale(store, employee, { account: "现金", cashDrawerConfirmed: true, items: [{ skuId: accessory.skuId, quantity: 1, salePrice: accessory.salePrice }] });
let preview = shift.snapshot(store, employee);
assert.equal(preview.salesCount, 1);
assert.equal(preview.expectedCash, sale.amount);
assert.equal(shift.snapshot(store, owner, employee.id).salesCount, 1);
assert.throws(() => shift.snapshot(store, employee, owner.id), /自己的交班账/);
const close = shift.submit(store, employee, { actualCash: sale.amount - 1, receiverId: owner.id, note: "测试差异" });
assert.equal(close.status, "待核对");
assert.equal(close.difference, -1);
assert.equal(store.feishuNotices.length, 1);
assert.equal(shift.snapshot(store, employee).salesCount, 0);
assert.throws(() => shift.submit(store, employee, { actualCash: 0, receiverId: owner.id, note: "" }), /现金有差异/);
shift.confirm(store, owner, { id: close.id, decision: "退回", note: "请重数" });
assert.equal(close.status, "待复核");
shift.revise(store, employee, { id: close.id, actualCash: sale.amount, note: "重数后相符" });
assert.equal(close.status, "待核对");
assert.equal(close.difference, 0);
shift.confirm(store, owner, { id: close.id, decision: "确认", note: "核对通过" });
assert.equal(close.status, "已确认");
assert.throws(() => shift.confirm(store, owner, { id: close.id, decision: "确认" }), /已处理/);
assert.equal(shift.closeouts(store, employee).length, 1);
console.log(JSON.stringify({ closeout: "passed", saleCount: preview.salesCount, cashDifferenceTest: -1, repeatedCount: shift.snapshot(store, employee).salesCount }));