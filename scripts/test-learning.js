const assert=require('node:assert/strict');
const {readStore}=require('../server/src/repository');
const learning=require('../server/src/learning');
const store=JSON.parse(JSON.stringify(readStore()));
const owner=store.users.find(x=>x.roleCode==='owner');
const trainee={id:'USR-LEARNING-TEST',name:'测试新员工',roleCode:'employee',status:'active',permissions:[]};
store.users.push(trainee);
const payload={type:'销售',event:'今天协助销售手机并核对顾客需求',learned:'学会了核对串码与收款方式的步骤',reflection:'下次先确认预算再向顾客推荐机型'};
const row=learning.create(store,trainee,payload);
assert.equal(row.status,'待审核');
assert.equal(learning.list(store,trainee).at(-1).id,row.id);
assert.throws(()=>learning.review(store,trainee,{id:row.id,approve:true,points:50}),{statusCode:403});
learning.review(store,owner,{id:row.id,approve:true,points:80,note:'记录具体'});
assert.equal(row.points,80);
assert.throws(()=>learning.review(store,owner,{id:row.id,approve:true,points:80}),/已审核/);
const second=learning.create(store,trainee,{...payload,type:'交班'});
assert.throws(()=>learning.review(store,owner,{id:second.id,approve:false}),/原因/);
learning.review(store,owner,{id:second.id,approve:false,note:'请补充具体步骤'});
assert.equal(second.points,0);
console.log(JSON.stringify({learning:'passed',submitted:2,ownerReview:true,duplicateReviewBlocked:true,liveDatabaseChanged:false}));
