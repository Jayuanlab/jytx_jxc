const assert=require('node:assert/strict');
const {readStore}=require('../server/src/repository');
const receptions=require('../server/src/receptions');
const conversions=require('../server/src/conversions');
const store=JSON.parse(JSON.stringify(readStore()));
const owner=store.users.find(x=>x.roleCode==='owner');
const a={id:'USR-CLAIM-A',name:'测试甲',roleCode:'employee',status:'active',permissions:['sale:create']};
const b={id:'USR-CLAIM-B',name:'测试乙',roleCode:'employee',status:'active',permissions:['sale:create']};
store.users.push(a,b);
const first=receptions.create(store,a,{phone:'13900000002',purpose:'购买手机',needs:'顾客想要续航好的手机',recommendation:'推荐了可售机型'});
first.createdAt='2026-10-01T02:00:00.000Z';
first.recommendation='已向顾客说明续航与价格差异';
receptions.close(store,a,{id:first.id,result:'未成交',noSaleReason:'再考虑',review:'顾客可能回店'});
receptions.confirmClose(store,owner,{id:first.id,validity:'有效',points:50});
const later=receptions.create(store,b,{phone:'13900000002',purpose:'购买手机'});
store.sales.push({id:'SO-CONVERSION-TEST',customerId:later.customerId,operatorId:b.id,salespersonId:b.id,salesperson:b.name,profit:1000});
store.commissionEntries.push({id:'COM-CONVERSION-TEST',orderId:'SO-CONVERSION-TEST',employeeId:b.id,kind:'sale',amount:100,mode:'profit'});
receptions.linkExisting(store,b,{receptionId:later.id,kind:'销售单',sourceId:'SO-CONVERSION-TEST'});
assert.equal(conversions.candidates(store,a,first.id).length,1);
const claim=conversions.submit(store,a,{sourceReceptionId:first.id,targetReceptionId:later.id,orderId:'SO-CONVERSION-TEST',contribution:'我第一次接待时讲解了机型续航和价格，顾客记住后再次到店购买'});
assert.equal(claim.status,'待老板判断');
assert.throws(()=>conversions.submit(store,a,{sourceReceptionId:first.id,targetReceptionId:later.id,orderId:'SO-CONVERSION-TEST',contribution:'再次申报同一笔转换贡献'}),/已申报/);
assert.throws(()=>conversions.review(store,b,{id:claim.id,approve:true,points:80}),/仅老板/);
conversions.review(store,owner,{id:claim.id,approve:true,points:80,note:'前次接待记录与成交关联充分'});
assert.equal(claim.status,'已认可');
const journey=receptions.journey(store,a,first.customerId);assert.equal(journey.visits.length,2);assert.ok(journey.events.some(x=>x.kind.includes('转化贡献')));
assert.equal(first.points.at(-1).amount,80);
assert.ok(later.assists.some(x=>x.conversionClaimId===claim.id&&x.status==='有效'));
const allocation=receptions.allocateCommission(store,owner,{id:later.id,assistId:claim.assistId,orderId:'SO-CONVERSION-TEST',beneficiaryId:a.id,rate:1});
assert.equal(allocation.amount,10);
console.log(JSON.stringify({conversion:'passed',sameCustomer:true,firstReceptionPreserved:true,ownerDecision:true,commissionFromOriginal:true,liveDatabaseChanged:false}));
