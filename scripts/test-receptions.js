const assert=require('node:assert/strict');
const {readStore}=require('../server/src/repository');
const r=require('../server/src/receptions');
const store=JSON.parse(JSON.stringify(readStore()));
const owner=store.users.find(x=>x.roleCode==='owner');
const clerk={id:'USR-RECEPTION-TEST',name:'测试店员',roleCode:'employee',status:'active',permissions:['sale:create']};
store.users.push(clerk);
const before={receptions:(store.receptions||[]).length,customers:(store.customers||[]).length};
const first=r.create(store,clerk,{phone:'13900000001',purpose:'购买手机',source:'到店',needs:'预算 2000 元'});
const second=r.create(store,clerk,{phone:'13900000001',purpose:'咨询套餐',source:'老顾客'});
assert.equal(first.customerId,second.customerId);
assert.notEqual(first.id,second.id);
assert.throws(()=>r.create(store,clerk,{phone:'123',purpose:'配件',source:'到店'}),/手机号/);
r.claimWechat(store,clerk,{id:first.id,evidence:'当面打开好友页面'});
r.confirmWechat(store,owner,{id:first.id,points:80});
assert.throws(()=>r.claimWechat(store,clerk,{id:second.id,evidence:'当面打开好友页面'}),/已领取/);
r.addAssist(store,clerk,{id:first.id,type:'协助销售',fromId:clerk.id,toId:owner.id,detail:'介绍机型'});
const assist=first.assists[0];
assert.throws(()=>r.addAssist(store,clerk,{id:first.id,type:'协助销售',fromId:clerk.id,toId:owner.id,detail:'介绍机型'}),/重复申报/);
r.confirmAssist(store,owner,{id:first.id,assistId:assist.id,approve:true,fromPoints:30,toPoints:60});
assert.equal(first.points.filter(x=>x.kind==='协助').length,2);
store.sales.push({id:'SO-RECEPTION-TEST',customerId:first.customerId,operatorId:clerk.id,salespersonId:clerk.id,salesperson:clerk.name,profit:1000,amount:1500});
store.commissionEntries.push({id:'COM-RECEPTION-TEST',orderId:'SO-RECEPTION-TEST',employeeId:clerk.id,kind:'sale',amount:100,mode:'profit'});
const noPhone=r.create(store,clerk,{purpose:'咨询配件',source:'到店'});
assert.equal(noPhone.customerId,null);
assert.throws(()=>r.linkCandidates(store,clerk,noPhone.id,'13900000001'),/不一致/);
assert.throws(()=>r.claimWechat(store,clerk,{id:noPhone.id,evidence:'好友页面'}),/无手机号/);
assert.throws(()=>r.linkCandidates(store,clerk,first.id,'13900000009'),/不一致/);
store.sales.push({id:'SO-OTHER-CUSTOMER',customerId:'CU-OTHER',operatorId:clerk.id,amount:300});
assert.deepEqual(r.linkCandidates(store,clerk,first.id,'13900000001').map(x=>x.id),['SO-RECEPTION-TEST']);
assert.throws(()=>r.linkExisting(store,clerk,{receptionId:first.id,kind:'销售单',sourceId:'SO-OTHER-CUSTOMER'}),/手机号/);
assert.throws(()=>r.linkExisting(store,clerk,{receptionId:first.id,kind:'销售单',sourceId:'SO-NO-PHONE'}),/不存在/);
r.linkExisting(store,clerk,{receptionId:first.id,kind:'销售单',sourceId:'SO-RECEPTION-TEST'});
assert.throws(()=>r.linkExisting(store,clerk,{receptionId:second.id,kind:'销售单',sourceId:'SO-RECEPTION-TEST'}),/已关联/);
const rental=require('../server/src/carrier-rentals');
assert.throws(()=>rental.create(store,clerk,{type:'card',serviceDate:'2026-10-07',externalOrderNo:'MB-WRONG-PHONE',customerPhone:'13900000009',receptionId:first.id,monthlyAmounts:[0]}),/不一致/);
const carrier=rental.create(store,clerk,{type:'card',serviceDate:'2026-10-07',externalOrderNo:'MB-SAME-PHONE',customerPhone:'13900000001',receptionId:first.id,monthlyAmounts:[0]});
assert.equal(carrier.customerId,first.customerId);
assert.equal(first.links.find(x=>x.kind==='移动业务单').id,carrier.id);
assert.equal(r.linkCandidates(store,clerk,first.id,'13900000001').length,0);

const allocation=r.allocateCommission(store,owner,{id:first.id,assistId:assist.id,orderId:'SO-RECEPTION-TEST',beneficiaryId:owner.id,rate:2});
assert.equal(allocation.amount,20);
assert.equal(store.commissionEntries.filter(x=>x.kind==='assist_transfer').reduce((n,x)=>n+x.amount,0),0);
assert.throws(()=>r.allocateCommission(store,owner,{id:first.id,assistId:assist.id,orderId:'SO-RECEPTION-TEST',beneficiaryId:owner.id,rate:2}),/已分配/);
store.commissionEntries.push({id:'COM-RECEPTION-RETURN',orderId:'SO-RECEPTION-TEST',employeeId:clerk.id,kind:'return',amount:-50});
store.saleReturns.push({id:'SR-RECEPTION-TEST',orderId:'SO-RECEPTION-TEST',profit:500});
r.reverseCommission(store,owner,store.sales.find(x=>x.id==='SO-RECEPTION-TEST'));
assert.equal(allocation.reversedAmount,10);
r.close(store,clerk,{id:first.id,result:'成交',review:'顾客关注续航'});
assert.throws(()=>r.confirmClose(store,clerk,{id:first.id,validity:'有效',points:100}),/仅老板/);
r.confirmClose(store,owner,{id:first.id,validity:'有效',points:100});
assert.equal(first.status,'已结案');
r.close(store,clerk,{id:noPhone.id,result:'未成交',noSaleReason:'无手机号',review:'已留底'});
assert.throws(()=>r.confirmClose(store,owner,{id:noPhone.id,validity:'有效',points:50}),/无手机号/);
r.confirmClose(store,owner,{id:noPhone.id,validity:'无效',points:50});
assert.equal(noPhone.points.at(-1).amount,50);

r.close(store,clerk,{id:second.id,result:'未成交',noSaleReason:'家人未定',review:'下周回访'});
assert.throws(()=>r.confirmClose(store,owner,{id:second.id,validity:'无效',points:49}),/积分/);
r.confirmClose(store,owner,{id:second.id,validity:'无效',points:50});
assert.equal(second.points.at(-1).amount,50);
assert.equal(r.list(store,clerk).rows.find(x=>x.id===first.id).customerPhone,'13900000001');
console.log(JSON.stringify({receptions:'passed',created:2,oneCustomer:true,wechatOnce:true,assistanceApproved:true,saleLinked:true,invalidMinimum:50,liveDatabaseChanged:false}));
