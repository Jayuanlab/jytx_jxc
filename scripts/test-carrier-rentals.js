const assert = require('node:assert/strict');
const {readStore} = require('../server/src/repository');
const rental = require('../server/src/carrier-rentals');
const store = JSON.parse(JSON.stringify(readStore()));
const user = store.users.find((row) => row.roleCode === 'owner');
const beforeReceipts = store.receipts.length;
const row = rental.create(store,user,{type:'broadband',serviceDate:'2026-10-07',externalOrderNo:'TEST-MB-20261007',monthlyAmounts:[20,30,40],note:'测试'});
assert.deepEqual(row.schedule.map((item)=>item.month),['2026-11','2026-12','2027-01']);
assert.throws(()=>rental.create(store,user,{type:'broadband',serviceDate:'2026-10-07',externalOrderNo:'TEST-MB-20261007',monthlyAmounts:[10]}),/已登记/);
let confirmed = rental.confirm(store,user,{id:row.id,month:'2026-11',amount:18,statementNo:'TEST-ST-11'});
assert.equal(confirmed.schedule[0].outstanding,18);
assert.throws(()=>rental.confirm(store,user,{id:row.id,month:'2026-11',amount:18,statementNo:'TEST-ST-11'}),/已确认/);
confirmed = rental.receive(store,user,{id:row.id,month:'2026-11',amount:10,bankRef:'TEST-BANK-1',account:'银行卡'});
assert.equal(confirmed.schedule[0].outstanding,8);
assert.equal(store.receipts.length,beforeReceipts+1);
assert.throws(()=>rental.receive(store,user,{id:row.id,month:'2026-11',amount:9,bankRef:'TEST-BANK-2',account:'银行卡'}),/超过/);
assert.throws(()=>rental.receive(store,user,{id:row.id,month:'2026-11',amount:1,bankRef:'TEST-BANK-1',account:'银行卡'}),/已登记/);
assert.ok((store.feishuNotices||[]).length>=3);
console.log(JSON.stringify({carrierServices:'passed',schedule:row.schedule.length,receiptsAdded:1,liveDatabaseChanged:false}));